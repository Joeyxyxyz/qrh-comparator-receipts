#!/usr/bin/env bash
# Start one of the kit's longer phases in the background and return at once, so that no single
# command has to stay in the foreground for more than a few seconds. Poll it with status.sh.
#
#   detach.sh LABEL SCRIPT [ARGS...]        e.g.   scripts/detach.sh deps 05_deps.sh
#
# Output goes to $QRH_WORK/logs/LABEL.log, the exit code to LABEL.exit. The job keeps running if
# the SSH connection drops. Not used for the Comparator run itself (06_run_comparator.sh detaches
# on its own, with the AF_UNIX restriction). The bridge phase gets that restriction here too.
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
require_not_root

[ "$#" -ge 2 ] || die "usage: detach.sh LABEL SCRIPT [ARGS...]"
label="$1"
script="$2"
shift 2
case "$label" in *[!A-Za-z0-9_-]*) die "label may only contain letters, digits, - and _" ;; esac
case "$label" in "$MAIN_LABEL" | "$DIRICHLET_LABEL" | control-* | upstream-*) die "that label belongs to the Comparator runs" ;; esac
case "$script" in *[!A-Za-z0-9_.]* | .* | "") die "SCRIPT must be a file name from scripts/, such as 05_deps.sh" ;; esac
[ -f "$KIT_DIR/scripts/$script" ] || die "no such script: scripts/$script"

job="$LOGS/$label.job.sh"
out="$LOGS/$label.log"
exitf="$LOGS/$label.exit"
startf="$LOGS/$label.start"
endf="$LOGS/$label.end"
unitf="$LOGS/$label.unit"

if job_running "$label"; then
  die "$label is already running ($(cat "$unitf")); see scripts/status.sh $label"
fi
if [ -e "$out" ] || [ -e "$exitf" ] || [ -e "$unitf" ]; then
  n=1
  while [ -e "$out.$n" ] || [ -e "$exitf.$n" ] || [ -e "$job.$n" ]; do n=$((n + 1)); done
  for f in "$job" "$out" "$exitf" "$startf" "$endf" "$unitf"; do
    if [ -e "$f" ]; then mv "$f" "$f.$n"; fi
  done
fi

args=""
for a in "$@"; do args="$args $(printf '%q' "$a")"; done

cat >"$job" <<EOF
#!/usr/bin/env bash
# Generated by detach.sh at $(ts): scripts/$script$args
export PATH="$PATH"
export QRH_WORK="$QRH_WORK"
export QRH_MATHLIB_FROM_SOURCE="$QRH_MATHLIB_FROM_SOURCE"
export QRH_DEV_NO_SANDBOX="$QRH_DEV_NO_SANDBOX"
export QRH_NO_SYSTEMD="$QRH_NO_SYSTEMD"
if [ -n "\${1:-}" ]; then echo "pid:\$\$" >"\$1"; fi
cd "$QRH_WORK" || exit 97
date -u +%Y-%m-%dT%H:%M:%SZ >"$startf"
/bin/bash "$KIT_DIR/scripts/$script"$args >"$out" 2>&1
rc=\$?
echo "\$rc" >"$exitf"
date -u +%Y-%m-%dT%H:%M:%SZ >"$endf"
exit "\$rc"
EOF
chmod +x "$job"

# The bridge phase needs its restricted unit; without a systemd user manager it cannot have one.
if [ "$script" = "08_bridge.sh" ] && [ "$QRH_NO_SYSTEMD" != "1" ] && ! have_user_systemd; then
  die "no systemd user manager, which the bridge phase needs. Log in over SSH as this user (not with su) and try again; see docs/TROUBLESHOOTING.md, \"Phase 1\""
fi
if [ "$QRH_NO_SYSTEMD" != "1" ] && have_user_systemd; then
  unit="qrhkit-$label-$(date -u +%Y%m%d%H%M%S)"
  props=(-p "OOMPolicy=continue")
  # The bridge phase loads OpenAI's compiled files, so it gets the unit restrictions of a
  # Comparator run. The other phases need the network and local services and do not load them.
  if [ "$script" = "08_bridge.sh" ]; then props=("${UNIT_PROPS[@]}"); fi
  echo "$unit" >"$unitf"
  if ! systemd-run --user --collect --quiet --unit "$unit" "${props[@]}" --working-directory "$QRH_WORK" -- /bin/bash "$job"; then
    rm -f "$unitf"
    die "$label: systemd-run could not start the unit"
  fi
else
  nohup setsid /bin/bash "$job" "$unitf" >/dev/null 2>&1 &
  sleep 1
fi
log "$label: scripts/$script started in the background ($(cat "$unitf" 2>/dev/null || echo starting)). Poll with: scripts/status.sh $label --wait 540" || true
