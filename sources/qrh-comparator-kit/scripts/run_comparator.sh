#!/usr/bin/env bash
# Run Comparator on one configuration, the way Comparator's README prescribes:
# as an unprivileged user, inside a systemd unit that forbids AF_UNIX sockets, with landrun
# as the sandbox for the build and export steps. Used for the controls and for the real run,
# so the controls exercise exactly the launch path the real run takes.
#
#   run_comparator.sh --label NAME --dir PROJECT_DIR --config CONFIG.json [--detach] [--run-type cold|warm]
#
# Not for direct use on the real proof: 06_run_comparator.sh is the only caller allowed to use
# the labels of the real runs, because it does the checks that must come first. It also passes
# --run-type, which makes the job itself record, at the moment it really starts, that an attempt
# began and of which kind. Nothing about an attempt depends on the launching terminal surviving.
#
# Files written under $QRH_WORK/logs:
#   NAME.job.sh   the exact command that was run        NAME.log    Comparator's output
#   NAME.exit     its exit code                         NAME.start, NAME.end   UTC timestamps
#   NAME.time     /usr/bin/time -v report               NAME.unit   systemd unit name (or pid:N)
#   NAME.mem.tsv  once a minute: time, then bytes of program memory (anon), file cache, swap
#   NAME.type     cold or warm (only with --run-type)
# Optional environment:
#   QRH_STACK_LIMIT=4G   a stack limit other than the kit's 1G for this run (recorded as a deviation)
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
require_not_root

label="" dir="" config="" detach=0 run_type=""
while [ "$#" -gt 0 ]; do
  case "$1" in
    --label) label="${2:-}"; shift 2 ;;
    --dir) dir="${2:-}"; shift 2 ;;
    --config) config="${2:-}"; shift 2 ;;
    --detach) detach=1; shift ;;
    --run-type) run_type="${2:-}"; shift 2 ;;
    *) die "run_comparator.sh: unknown argument $1" ;;
  esac
done
[ -n "$label" ] && [ -n "$dir" ] && [ -n "$config" ] || die "usage: run_comparator.sh --label NAME --dir DIR --config FILE [--detach] [--run-type cold|warm]"
case "$run_type" in "" | cold | warm) ;; *) die "--run-type must be cold or warm" ;; esac
case "$label" in *[!A-Za-z0-9_-]*) die "label may only contain letters, digits, - and _" ;; esac
case "$label" in
  "$MAIN_LABEL" | "$DIRICHLET_LABEL")
    [ "${QRH_CALLED_BY_06:-}" = "1" ] || die "the real runs are started with scripts/06_run_comparator.sh, which does the checks that must come first"
    ;;
esac
[ -d "$dir" ] || die "project directory not found: $dir"
[ -f "$dir/$config" ] || die "config not found: $dir/$config"
[ -x "$COMPARATOR_BIN" ] || die "Comparator is not built; run phase 2: $(phase_command 2)"
[ -x "$LEAN4EXPORT_BIN" ] || die "lean4export is not built; run phase 2: $(phase_command 2)"
[ -x "$LANDRUN_BIN" ] || die "landrun is not built; run phase 2: $(phase_command 2)"

job="$LOGS/$label.job.sh"
out="$LOGS/$label.log"
exitf="$LOGS/$label.exit"
startf="$LOGS/$label.start"
endf="$LOGS/$label.end"
timef="$LOGS/$label.time"
unitf="$LOGS/$label.unit"
memf="$LOGS/$label.mem.tsv"
typef="$LOGS/$label.type"

# Refuse to start a second copy of a run that is still going.
if job_running "$label"; then
  die "$label is already running ($(cat "$unitf")); see scripts/status.sh $label"
fi

# Keep earlier attempts: NAME.log -> NAME.log.1, .2, ...
if [ -e "$out" ] || [ -e "$exitf" ] || [ -e "$unitf" ] || [ -e "$startf" ] || [ -e "$job" ] || [ -e "$typef" ]; then
  n="$(archive_attempt "$label")"
  log "$label: previous attempt archived with suffix .$n"
fi

prefix=""
if [ -x /usr/bin/time ]; then prefix="/usr/bin/time -v -o '$timef'"; fi

# What the job records about itself when it really starts. For the real runs (--run-type) that
# is: that an attempt of this kind began, and, for the main run, the phase-6 marker. For every
# run: whether its own process may create an AF_UNIX socket (it must not), and its stack limit.
record=""
if [ -n "$run_type" ]; then
  record="echo '$run_type' >'$typef'
fact_line 'attempt_started_$label' '$run_type'"
  if [ "$label" = "$MAIN_LABEL" ]; then
    record="$record
date -u +%Y-%m-%dT%H:%M:%SZ >'$RECEIPT/phase_6.ok'
fact_line 'phase_6' 'ok'"
  fi
fi

cat >"$job" <<EOF
#!/usr/bin/env bash
# Generated by run_comparator.sh at $(ts). This is the exact command that was run for "$label".
export PATH="$PATH"
export COMPARATOR_LANDRUN="$LANDRUN_BIN"
export COMPARATOR_LEAN4EXPORT="$LEAN4EXPORT_BIN"
if [ -n "\${1:-}" ]; then echo "pid:\$\$" >"\$1"; fi
fact_line() { printf '%s\t%s\t%s\n' "\$(date -u +%Y-%m-%dT%H:%M:%SZ)" "\$1" "\$2" >>"$RECEIPT/facts.tsv"; }
fact_line 'job_af_unix_$label' "\$(python3 -I -c '
import socket
try:
    socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
    print("allowed")
except OSError:
    print("denied")
' 2>/dev/null || echo unknown)"
fact_line 'job_stack_kb_$label' "\$(ulimit -s)"
fact_line 'job_boot_id_$label' "\$(cat /proc/sys/kernel/random/boot_id 2>/dev/null || echo unknown)"
cd "$dir" || exit 97
date -u +%Y-%m-%dT%H:%M:%SZ >"$startf"
$record
# Bookkeeping only: once a minute, the memory of this job's control group.
cg="/sys/fs/cgroup\$(awk -F: '\$1 == "0" { print \$3 }' /proc/self/cgroup 2>/dev/null)"
sampler=""
if [ "$QRH_NO_SYSTEMD" != "1" ] && [ -r "\$cg/memory.stat" ]; then
  ( while sleep 60; do
      printf '%s\t%s\t%s\t%s\n' "\$(date -u +%Y-%m-%dT%H:%M:%SZ)" \\
        "\$(awk '\$1 == "anon" { print \$2 }' "\$cg/memory.stat" 2>/dev/null)" \\
        "\$(awk '\$1 == "file" { print \$2 }' "\$cg/memory.stat" 2>/dev/null)" \\
        "\$(cat "\$cg/memory.swap.current" 2>/dev/null)"
    done >"$memf" 2>/dev/null ) &
  sampler=\$!
fi
$prefix lake env "$COMPARATOR_BIN" "$config" >"$out" 2>&1
rc=\$?
if [ -n "\$sampler" ]; then kill "\$sampler" 2>/dev/null; fi
echo "\$rc" >"$exitf"
date -u +%Y-%m-%dT%H:%M:%SZ >"$endf"
exit "\$rc"
EOF
chmod +x "$job"

if [ "$QRH_NO_SYSTEMD" = "1" ]; then
  case "$label" in
    control-* | upstream-*) ;; # the self-test records one line for all controls
    *) deviation "$label: launched WITHOUT systemd-run, so AF_UNIX sockets were not restricted (QRH_NO_SYSTEMD=1). INVALID as a certification." ;;
  esac
  fact invalidating_override "QRH_NO_SYSTEMD"
  if [ "$detach" = "1" ]; then
    fact "launch_mode_$label" "no-systemd"
    nohup setsid /bin/bash "$job" "$unitf" >/dev/null 2>&1 &
    sleep 1
    log "$label: started in the background ($(cat "$unitf" 2>/dev/null || echo starting)). Follow it with scripts/status.sh $label" || true
    exit 0
  fi
  fact "launch_mode_$label" "no-systemd"
  /bin/bash "$job" || true
else
  have_user_systemd || die "no systemd user manager; log in over SSH as this user after 00_system_setup.sh (see docs/TROUBLESHOOTING.md)"
  unit="qrhkit-$label-$(date -u +%Y%m%d%H%M%S)"
  props=("${UNIT_PROPS[@]}")
  mode_text="systemd-user $UNIT_PROPS_TEXT"
  if [ -n "${QRH_STACK_LIMIT:-}" ]; then
    props+=(-p "LimitSTACK=$QRH_STACK_LIMIT")
    mode_text="$mode_text (stack limit set to $QRH_STACK_LIMIT for this run)"
    deviation "$label: stack limit set to $QRH_STACK_LIMIT instead of the kit's 1G"
  fi
  # Recorded before the launch, and everything after the launch is allowed to fail: if the
  # terminal that started the run goes away at this very moment, the run is still fully on record.
  fact "launch_mode_$label" "$mode_text"
  if [ "$detach" = "1" ]; then
    echo "$unit" >"$unitf"
    if ! systemd-run --user --collect --quiet --unit "$unit" "${props[@]}" --working-directory "$dir" -- /bin/bash "$job"; then
      rm -f "$unitf"
      die "$label: systemd-run could not start the unit"
    fi
    log "$label: started as systemd user unit $unit. Follow it with scripts/status.sh $label" || true
    exit 0
  fi
  systemd-run --user --wait --collect --quiet --unit "$unit" "${props[@]}" --working-directory "$dir" -- /bin/bash "$job" || true
fi

[ -f "$exitf" ] || die "$label: the job did not record an exit code (see $out)"
rc="$(cat "$exitf")"
log "$label: Comparator exited with $rc"
exit "$rc"
