"""Generate the Comparator challenge for the MNF.RH layer on top of the zeta23 checkout (step B2).

Run from the project directory (zeta23/) after MNF/RH/*.lean are in place:
    python3 -I <addon>/scripts/z23_gen_challenge.py

One Mathlib-only challenge module per MNF source module, mirroring it exactly (same Mathlib
imports, same `open`s, the definitions copied verbatim and in order, every theorem named in
MNFChallenges/theorem_list.txt with its proof replaced by `sorry`): Lean abstracts the proof
terms inside a definition (such as the `Nat.AtLeastTwo` instance inside `1 / 2`) into auxiliary
lemmas that are shared per module, so a challenge that is not module-for-module the same as the
sources would give some definition a different auxiliary lemma and Comparator, which compares
definition bodies (`definition_names` is empty), would reject it. The last module,
MNFChallenges/Restated.lean, mirrors MNF/RH/Zeta23Restated.lean minus its non-Mathlib
imports (Solution, the zeta23 side); its statements mention only MNF constants and Mathlib.
"""
import json
import re
from pathlib import Path

SOURCES = [
    ("MNF/RH/Core.lean", "MNFChallenges/Core.lean", None),
    ("MNF/RH/Gap.lean", "MNFChallenges/Gap.lean", "MNFChallenges.Core"),
    ("MNF/RH/Hypotheses.lean", "MNFChallenges/Hypotheses.lean", "MNFChallenges.Gap"),
    ("MNF/RH/Counting.lean", "MNFChallenges/Counting.lean", "MNFChallenges.Hypotheses"),
    ("MNF/RH/Zeta23Restated.lean", "MNFChallenges/Restated.lean", "MNFChallenges.Counting"),
]
CHALLENGE_MODULE = "MNFChallenges.Restated"
SOLUTION_MODULE = "MNF.RH.Zeta23Restated"
want_thms = Path("MNFChallenges/theorem_list.txt").read_text().split()
HEADER = [
    "/-", "MNF × RIEMANN ZETA on the zeta23 tree — COMPARATOR CHALLENGE  ({out})",
    "Mirror of {src}: its Mathlib imports and `open`s, its definitions copied verbatim and in",
    "order, and every theorem of MNFChallenges/theorem_list.txt with the proof replaced by `sorry`.",
    "Generated by z23_gen_challenge.py; the challenge is " + CHALLENGE_MODULE + ", which imports the",
    "other mirror modules and nothing of zeta23. Comparator builds the challenge and the solution",
    "(" + SOLUTION_MODULE + "), exports both, and checks that every theorem statement and every",
    "definition (name, type and body: `definition_names` is empty) agrees, and that the solution's",
    "proofs use no axiom beyond propext, Quot.sound, Classical.choice.", "-/",
]
Path("MNFChallenges").mkdir(exist_ok=True)
all_defs, all_thms = [], []
for src, out, prev in SOURCES:
    lines = Path(src).read_text().split("\n")
    imports = [l for l in lines if l.startswith("import Mathlib")]
    opens = [l for l in lines if l.startswith("open ")]
    defs, thms = [], []
    i = 0
    while i < len(lines):
        l = lines[i]
        m = re.match(r"^(noncomputable def|def|theorem) (\S+)", l)
        if m:
            kind, name = m.group(1), m.group(2)
            block = [l]
            j = i
            while not (lines[j].rstrip().endswith(":= by") or lines[j].rstrip().endswith(":=")):
                if kind != "theorem" and ":=" in lines[j]:
                    break
                j += 1
                block.append(lines[j])
            if kind == "theorem":
                if name in want_thms:
                    text = "\n".join(block)
                    text = re.sub(r":= by\s*$", ":= by\n  sorry", text)
                    if not text.endswith("sorry"):
                        text = re.sub(r":=\s*$", ":=\n  sorry", text)
                    thms.append((name, text))
            else:
                k = i
                while k + 1 < len(lines) and lines[k + 1].strip() != "":
                    k += 1
                defs.append((name, "\n".join(lines[i:k + 1])))
            i = j + 1
        else:
            i += 1
    body = [h.format(out=out, src=src) for h in HEADER]
    body += ([f"import {prev}"] if prev else []) + imports + [""] + ["namespace MNF.RH", ""] + opens + [""]
    for n, d in defs:
        body += [d, ""]
    for n, t in thms:
        body += [t, ""]
    body.append("end MNF.RH")
    Path(out).write_text("\n".join(body) + "\n")
    all_defs += defs
    all_thms += thms
    print(f"{out}: {len(defs)} definitions, {len(thms)} theorems")
missing = [n for n in want_thms if n not in [t[0] for t in all_thms]]
assert not missing, missing
order = {n: k for k, n in enumerate(want_thms)}
cfg = {"challenge_module": CHALLENGE_MODULE, "solution_module": SOLUTION_MODULE,
       "theorem_names": ["MNF.RH." + n for n in sorted([t[0] for t in all_thms], key=order.get)],
       "definition_names": [],
       "permitted_axioms": ["propext", "Quot.sound", "Classical.choice"], "enable_nanoda": True}
Path("MNFChallenges/Restated.json").write_text(json.dumps(cfg, indent=2) + "\n")
audit = ["/- Audit of the MNF.RH layer on the zeta23 tree: axiom reports and printed statements for every",
         "   theorem the Comparator challenge names. Compiled by z23_mnf_report.sh with plain `lean`,",
         "   sandboxed, against the tree Comparator built. -/",
         f"import {SOLUTION_MODULE}", ""]
audit += [f"#print axioms MNF.RH.{n}" for n, _ in all_thms] + [""] + [f"#check MNF.RH.{n}" for n, _ in all_thms]
Path("MNF_AuditB2.lean").write_text("\n".join(audit) + "\n")
print(len(all_defs), "definitions,", len(all_thms), "theorems; config MNFChallenges/Restated.json; MNF_AuditB2.lean")
