"""Generate the Comparator challenge for the MNF.RH library (add-on v3).

One challenge module per source module, mirroring it exactly: the same Mathlib imports, the same
preamble (`namespace`, `open`, `set_option`, `noncomputable section`, in source order), the same
definitions and structures copied verbatim and in order, and every theorem of
MNFChallenges/theorem_list.txt with its proof replaced by `sorry`; then MNFChallenges/RH.lean,
which imports the mirrors and carries the statements of MNF/RH/Unconditional.lean (whose OpenAI
import is NOT reproduced: the challenge imports Mathlib only).

Why mirror module by module: Lean abstracts the proof terms inside a definition (such as the
`Nat.AtLeastTwo` instance inside `1/2 : ℝ`) into auxiliary lemmas named `<decl>._proof_n` and
reuses one already created in the same module, so a challenge with a different module structure
gives some definition a different auxiliary lemma, and Comparator, which compares definition
bodies (`definition_names` is empty), rejects the pair although the text is the same.  Found by
the v2 pre-check on 2026-10-28.  A second rule, found by the zeta23 add-on's pre-check the same
day: no theorem statement may mention another theorem as a term, because Comparator compares a
theorem reached that way in full, proof included.

Sources, in order (challenge module ← source; `ns` is the namespace the file opens, None for the
root namespace; the Sturm–Liouville file is Joey's consolidated corpus file with its own
preamble):
"""
import json
import re
from pathlib import Path

SOURCES = [
    # (source file, challenge file, challenge module, previous challenge module(s), namespace)
    ("MNF/RH/Core.lean", "MNFChallenges/Core.lean", "MNFChallenges.Core", [], "MNF.RH"),
    ("MNF/RH/Gap.lean", "MNFChallenges/Gap.lean", "MNFChallenges.Gap", ["MNFChallenges.Core"], "MNF.RH"),
    ("MNF/RH/Hypotheses.lean", "MNFChallenges/Hypotheses.lean", "MNFChallenges.Hypotheses", ["MNFChallenges.Gap"], "MNF.RH"),
    ("MNF/RH/Counting.lean", "MNFChallenges/Counting.lean", "MNFChallenges.Counting", ["MNFChallenges.Hypotheses"], "MNF.RH"),
    ("MNF/RH/Reduction.lean", "MNFChallenges/Reduction.lean", "MNFChallenges.Reduction", ["MNFChallenges.Hypotheses"], "MNF.RH"),
    ("SturmLiouville/SimpleEigenvalues.lean", "MNFChallenges/SturmLiouville.lean", "MNFChallenges.SturmLiouville", [], None),
    ("MNF/RH/Schrodinger.lean", "MNFChallenges/Schrodinger.lean", "MNFChallenges.Schrodinger", ["MNFChallenges.SturmLiouville", "MNFChallenges.Reduction"], "MNF.RH"),
    ("MNF/RH/GapDensity.lean", "MNFChallenges/GapDensity.lean", "MNFChallenges.GapDensity", ["MNFChallenges.Counting"], "MNF.RH"),
    ("MNF/RH/Unconditional.lean", "MNFChallenges/RH.lean", "MNFChallenges.RH", ["MNFChallenges.Schrodinger", "MNFChallenges.GapDensity"], "MNF.RH"),
]
want_thms = Path("MNFChallenges/theorem_list.txt").read_text().split()
DECL_RE = re.compile(r"^(noncomputable def|def|structure|theorem|lemma) (\S+)")
PREAMBLE_RE = re.compile(r"^(open |open$|set_option |noncomputable section\s*$|namespace )")
HEADER = [
    "/-", "MNF × RIEMANN ZETA — COMPARATOR CHALLENGE  ({out})",
    "Mirror of {src}: its Mathlib imports and preamble, its definitions and structures copied verbatim",
    "and in order, and every theorem of MNFChallenges/theorem_list.txt with the proof replaced by",
    "`sorry`.  Generated by scripts/gen_challenge.py; the challenge is MNFChallenges.RH, which imports",
    "the other mirror modules.  Comparator builds the challenge and the solution (MNF.RH.Unconditional),",
    "exports both, and checks that every theorem statement and every definition (name, type and body:",
    "`definition_names` is empty, so nothing is a hole) agrees, and that the solution's proofs use no",
    "axiom beyond propext, Quot.sound, Classical.choice.", "-/",
]


def block_end(lines, i, kind):
    """Index of the last line of the declaration starting at line i."""
    if kind in ("theorem", "lemma"):
        j = i
        while not (lines[j].rstrip().endswith(":= by") or lines[j].rstrip().endswith(":=")):
            j += 1
        return j  # the signature ends here; the proof follows (dropped)
    j = i
    while j + 1 < len(lines) and lines[j + 1].strip() != "":
        j += 1
    return j


all_thms, all_defs, all_structs = [], [], []
for src, out, mod, prevs, ns in SOURCES:
    lines = Path(src).read_text().split("\n")
    imports = [l for l in lines if l.startswith("import Mathlib")]
    preamble, decls = [], []
    i, seen_decl = 0, False
    while i < len(lines):
        l = lines[i]
        m = DECL_RE.match(l)
        if m:
            seen_decl = True
            kind, name = m.group(1), m.group(2)
            j = block_end(lines, i, kind)
            if kind == "theorem":
                if name in want_thms:
                    text = "\n".join(lines[i:j + 1])
                    text = re.sub(r":= by\s*$", ":= by\n  sorry", text)
                    if not text.endswith("sorry"):
                        text = re.sub(r":=\s*$", ":=\n  sorry", text)
                    decls.append(("theorem", name, text))
                    all_thms.append((ns, name))
            elif kind == "lemma":
                pass  # helper lemmas of the Sturm–Liouville file are never challenge statements
            else:
                decls.append((kind, name, "\n".join(lines[i:j + 1])))
                (all_structs if kind == "structure" else all_defs).append((ns, name))
            i = j + 1
        else:
            if not seen_decl and PREAMBLE_RE.match(l):
                preamble.append(l)
            i += 1
    body = [h.format(out=out, src=src) for h in HEADER]
    body += [f"import {p}" for p in prevs] + imports + [""]
    body += preamble + [""]
    for kind, name, text in decls:
        body += [text, ""]
    closers = []
    if any(l.startswith("namespace ") for l in preamble):
        closers.append("end " + [l for l in preamble if l.startswith("namespace ")][0].split()[1])
    if any(l.startswith("noncomputable section") for l in preamble):
        closers.insert(0, "end")
    body += closers
    Path(out).write_text("\n".join(body) + "\n")
    n_t = sum(1 for d in decls if d[0] == "theorem")
    print(f"{out}: {len(decls) - n_t} definitions/structures, {n_t} theorems")

missing = [n for n in want_thms if n not in [t[1] for t in all_thms]]
assert not missing, missing
order = {n: k for k, n in enumerate(want_thms)}
full = lambda ns, n: (ns + "." + n) if ns else n
names = [full(ns, n) for ns, n in sorted(all_thms, key=lambda t: order[t[1]])]
cfg = {"challenge_module": "MNFChallenges.RH", "solution_module": "MNF.RH.Unconditional",
       "theorem_names": names, "definition_names": [],
       "permitted_axioms": ["propext", "Quot.sound", "Classical.choice"], "enable_nanoda": False}
Path("MNFChallenges/RH.json").write_text(json.dumps(cfg, indent=2) + "\n")
audit = ["/- Audit of the MNF.RH library (v3): axiom reports and printed statements for every theorem the",
         "   Comparator challenge names. Compiled by scripts/mnf_report.sh with plain `lean`, sandboxed,",
         "   against the tree Comparator built. -/", "import MNF.RH.Unconditional", ""]
audit += [f"#print axioms {n}" for n in names] + [""] + [f"#check {n}" for n in names]
Path("MNF_Audit.lean").write_text("\n".join(audit) + "\n")
print(len(all_defs), "definitions,", len(all_structs), "structures,", len(all_thms), "theorems")
