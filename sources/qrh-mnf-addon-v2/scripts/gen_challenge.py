"""Generate the Comparator challenge for the MNF.RH library (add-on v2).

One challenge module per source module, mirroring MNF/RH/{Core,Gap,Hypotheses}.lean exactly
(same imports, same `open`s, same definitions in the same order, every theorem of the list with
its proof replaced by `sorry`), plus MNFChallenges/RH.lean, which imports them and carries the
statements of MNF/RH/Unconditional.lean (whose definitions are all in the three files above; its
OpenAI import is NOT reproduced: the challenge imports Mathlib only).

Why mirror the modules: when Lean elaborates a definition it abstracts nested proof terms (such
as the `Nat.AtLeastTwo` instance inside a real numeral like `1/2`) into auxiliary lemmas named
`<decl>._proof_n`, and reuses an identical auxiliary lemma already created *in the same module*.
A single-file challenge would therefore give `LeftCriticalStrip` the auxiliary lemma of
`ShiftedZeroSpectrum`, while in the sources (different files) it gets its own, and Comparator,
asked to compare definition bodies (`definition_names` is empty), would reject the pair although
the two definitions are the same text.  Mirroring the module structure makes the bodies identical
constant for constant.  (Found by the local pre-check of v2, 2026-10-28.)
"""
import json
import re
from pathlib import Path

SOURCES = [
    ("MNF/RH/Core.lean", "MNFChallenges/Core.lean", "MNFChallenges.Core", None),
    ("MNF/RH/Gap.lean", "MNFChallenges/Gap.lean", "MNFChallenges.Gap", "MNFChallenges.Core"),
    ("MNF/RH/Hypotheses.lean", "MNFChallenges/Hypotheses.lean", "MNFChallenges.Hypotheses", "MNFChallenges.Gap"),
    ("MNF/RH/Unconditional.lean", "MNFChallenges/RH.lean", "MNFChallenges.RH", "MNFChallenges.Hypotheses"),
]
want_thms = Path("MNFChallenges/theorem_list.txt").read_text().split()
HEADER = [
    "/-", "MNF × RIEMANN ZETA — COMPARATOR CHALLENGE  ({out})",
    "Mirror of {src}: its Mathlib imports and `open`s, its definitions copied verbatim and in",
    "order, and every theorem of MNFChallenges/theorem_list.txt with the proof replaced by `sorry`.",
    "Generated by scripts/gen_challenge.py; the challenge is MNFChallenges.RH, which imports the",
    "other three modules. Comparator builds the challenge and the solution (MNF.RH.Unconditional),",
    "exports both, and checks that every theorem statement and every definition (name, type and",
    "body: `definition_names` is empty, so nothing is a hole) agrees, and that the solution's",
    "proofs use no axiom beyond propext, Quot.sound, Classical.choice.", "-/",
]

all_defs, all_thms = [], []
for src, out, mod, prev in SOURCES:
    lines = Path(src).read_text().split("\n")
    imports = [l for l in lines if l.startswith("import Mathlib")]
    opens = [l for l in lines if l.startswith("open ")]
    defs, thms = [], []
    i = 0
    while i < len(lines):
        l = lines[i]
        m = re.match(r"^(noncomputable def|def|theorem) (\S+)", l)
        if m:
            kind, name = m.group(1), m.group(2)
            block = [l]
            j = i
            while not (lines[j].rstrip().endswith(":= by") or lines[j].rstrip().endswith(":=")):
                if kind != "theorem" and ":=" in lines[j]:
                    break
                j += 1
                block.append(lines[j])
            if kind == "theorem":
                if name in want_thms:
                    text = "\n".join(block)
                    text = re.sub(r":= by\s*$", ":= by\n  sorry", text)
                    if not text.endswith("sorry"):
                        text = re.sub(r":=\s*$", ":=\n  sorry", text)
                    thms.append((name, text))
            else:
                k = i
                while k + 1 < len(lines) and lines[k + 1].strip() != "":
                    k += 1
                defs.append((name, "\n".join(lines[i:k + 1])))
            i = j + 1
        else:
            i += 1
    body = [h.format(out=out, src=src) for h in HEADER]
    body += ([f"import {prev}"] if prev else []) + imports + [""] + ["namespace MNF.RH", ""] + opens + [""]
    for n, d in defs:
        body += [d, ""]
    for n, t in thms:
        body += [t, ""]
    body.append("end MNF.RH")
    Path(out).write_text("\n".join(body) + "\n")
    all_defs += defs
    all_thms += thms
    print(f"{out}: {len(defs)} definitions, {len(thms)} theorems")

missing = [n for n in want_thms if n not in [t[0] for t in all_thms]]
assert not missing, missing
order = {n: k for k, n in enumerate(want_thms)}
cfg = {"challenge_module": "MNFChallenges.RH", "solution_module": "MNF.RH.Unconditional",
       "theorem_names": ["MNF.RH." + n for n in sorted([t[0] for t in all_thms], key=order.get)],
       "definition_names": [],
       "permitted_axioms": ["propext", "Quot.sound", "Classical.choice"], "enable_nanoda": False}
Path("MNFChallenges/RH.json").write_text(json.dumps(cfg, indent=2) + "\n")
print(len(all_defs), "definitions,", len(all_thms), "theorems")
