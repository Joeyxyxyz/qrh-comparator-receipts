"""Mirror generator for the density layer on the zeta23 tree (extends z23_gen_challenge.py:
abbrev, noncomputable section, per-source namespace, several imports). Run from zeta23/."""
import json, re
from pathlib import Path
SOURCES = [
  ("MNF/RH/Core.lean",       "MNFChallenges/Core.lean",       [],                        "MNF.RH", False),
  ("MNF/RH/Gap.lean",        "MNFChallenges/Gap.lean",        ["MNFChallenges.Core"],    "MNF.RH", False),
  ("MNF/RH/Hypotheses.lean", "MNFChallenges/Hypotheses.lean", ["MNFChallenges.Gap"],     "MNF.RH", False),
  ("MNF/RH/Counting.lean",   "MNFChallenges/Counting.lean",   ["MNFChallenges.Hypotheses"], "MNF.RH", False),
  ("MNF/RH/GapDensity.lean", "MNFChallenges/GapDensity.lean", ["MNFChallenges.Counting"], "MNF.RH", False),
  ("MNF/RH/Density.lean",    "MNFChallenges/Density.lean",    ["MNFChallenges.GapDensity"], "MNF.RH", False),
  ("MNF/Extension/InjectionEjection.lean", "MNFChallenges/Extension.lean", [], "MNF.Extension", True),
  ("MNF/RH/Strip.lean",      "MNFChallenges/Strip.lean",      ["MNFChallenges.Density", "MNFChallenges.Extension"], "MNF.RH", False),
]
CHALLENGE_MODULE, SOLUTION_MODULE = "MNFChallenges.Strip", "MNF.RH.Strip"
want = {}  # module -> list of theorem names to list in the config (all theorems of the later modules)
all_thms = []
for src, out, prevs, ns, noncomp in SOURCES:
    lines = Path(src).read_text().split("\n")
    imports = [l for l in lines if l.startswith("import Mathlib")]
    opens = [l for l in lines if l.startswith("open ") and not l.startswith("open MNF.Extension")]
    opens += [l for l in lines if l.startswith("open MNF.Extension")]
    setopts = [l for l in lines if l.startswith("set_option") and "maxHeartbeats" not in l]
    defs, thms = [], []
    i = 0
    while i < len(lines):
        l = lines[i]
        m = re.match(r"^(noncomputable def|def|abbrev|theorem|lemma) (\S+)", l)
        if not m:
            i += 1
            continue
        kind, name = m.group(1), m.group(2)
        # a declaration block runs while the following lines are indented (continuations, match arms)
        k = i
        while k + 1 < len(lines) and lines[k + 1].startswith((" ", "\t")) and lines[k + 1].strip() != "":
            k += 1
        block = lines[i:k + 1]
        if kind in ("theorem", "lemma"):
            text = "\n".join(block)
            j = text.index(":=")          # statements here contain no `:=`; the first one starts the proof
            text = text[:j] + ":= by\n  sorry"
            thms.append((name, text))
            if src in ("MNF/RH/GapDensity.lean", "MNF/RH/Density.lean", "MNF/RH/Strip.lean", "MNF/Extension/InjectionEjection.lean") and not name.startswith("aux_"):
                all_thms.append(ns + "." + name)
        else:
            defs.append((name, "\n".join(block)))
        i = k + 1
    body = ["/-", f"MNF × RIEMANN ZETA on the zeta23 tree — COMPARATOR CHALLENGE ({out})",
            f"Mirror of {src}: its Mathlib imports, opens and set_options, its definitions copied verbatim and in",
            "order, and every theorem with the proof replaced by `sorry`. Generated by gen_density_challenge.py",
            f"(density layer, 2026-11-03); the challenge is {CHALLENGE_MODULE}, the solution {SOLUTION_MODULE}.", "-/"]
    body += [f"import {p}" for p in prevs] + imports + [""] + setopts + (["noncomputable section"] if noncomp else []) + [f"namespace {ns}", ""] + opens + [""]
    for n, d in defs: body += [d, ""]
    for n, t in thms: body += [t, ""]
    body.append(f"end {ns}")
    if noncomp: body.append("end")
    Path(out).write_text("\n".join(body) + "\n")
    print(f"{out}: {len(defs)} definitions, {len(thms)} theorems")
cfg = {"challenge_module": CHALLENGE_MODULE, "solution_module": SOLUTION_MODULE, "theorem_names": all_thms,
       "definition_names": [], "permitted_axioms": ["propext", "Quot.sound", "Classical.choice"], "enable_nanoda": True}
Path("MNFChallenges/Strip.json").write_text(json.dumps(cfg, indent=2) + "\n")
audit = ["import MNF.RH.Strip", ""] + [f"#print axioms {n}" for n in all_thms]
Path("MNF_AuditDensity.lean").write_text("\n".join(audit) + "\n")
print(len(all_thms), "theorems listed in MNFChallenges/Strip.json")
